"""Three-way Hessian discrepancy decomposition at each rotation and block.

Exact identity (coordinate-wise):
  H_NNfit - H_exact =
      (H_formulaFit - H_exact) + (H_NNfit - H_formulaFit).

First term is the observed regression/sampling approximation discrepancy
even when numerical Y was generated by the analytic model. Second is the
difference between TWO responses fitted by the SAME estimator; it is
NOT automatically the true NN function's Hessian difference.
For binary Choice the two Y channels have different stochastic semantics
(Bernoulli samples vs NN hard-threshold outcomes), so attribution is weaker.
"""
from __future__ import annotations
import numpy as np
from metrics import block_array


def three_way_gap(exact,formula_fit,nn_fit,block,validity=None,channel=""):
    a=np.asarray(block_array(exact,block),dtype=float).ravel()
    f=np.asarray(block_array(formula_fit,block),dtype=float).ravel()
    n=np.asarray(block_array(nn_fit,block),dtype=float).ravel()
    keep=np.isfinite(a)&np.isfinite(f)&np.isfinite(n)
    if validity is not None:
        v=np.asarray(block_array(validity,block),dtype=float).ravel()
        keep &=np.isfinite(v)&(v>0)
    a,f,n=a[keep],f[keep],n[keep]
    if not len(a):return {"n_elements":0}
    # Exact telescoping decomposition; a violation indicates a code bug.
    est=f-a
    gap=n-f
    total=n-a
    if not np.allclose(est+gap,total,atol=1e-12,rtol=1e-12):
        raise AssertionError("Three-way Hessian residuals do not telescope")
    norm_a=float(np.linalg.norm(a))
    denom=max(norm_a,1e-15)
    norm_est=float(np.linalg.norm(est))
    norm_gap=float(np.linalg.norm(gap))
    norm_total=float(np.linalg.norm(total))
    cross=float(np.dot(est,gap))
    expected=norm_est**2+norm_gap**2+2*cross
    if not np.isclose(expected,norm_total**2,atol=1e-12,rtol=1e-10):
        raise AssertionError("Three-way sum-of-squares identity failed")
    def cosine(x,y):
        nx=float(np.linalg.norm(x))
        ny=float(np.linalg.norm(y))
        return float(x@y/(nx*ny)) if nx>1e-15 and ny>1e-15 else None
    return dict(
        n_elements=len(a),
        exact_h_norm=norm_a,
        formula_fit_error_abs=norm_est,
        formula_fit_error_rel=float(norm_est/denom),
        nn_minus_formula_abs=norm_gap,
        nn_minus_formula_rel=float(norm_gap/denom),
        nn_fit_total_error_abs=norm_total,
        nn_fit_total_error_rel=float(norm_total/denom),
        formula_fit_vs_nn_fit_cosine=cosine(f,n),
        exact_vs_formula_fit_cosine=cosine(a,f),
        exact_vs_nn_fit_cosine=cosine(a,n),
        residual_alignment_cosine=cosine(est,gap),
        squared_error_interaction=2*cross,
        squared_error_fraction_est=norm_est**2/max(norm_total**2,1e-30),
        squared_error_fraction_gap=norm_gap**2/max(norm_total**2,1e-30),
        binary_choice_semantics_not_comparable=channel=="choice",
    )


def three_way_all(nine,validity_by_target,blocks):
    """Evaluate analytic, analytic-Y fit and NN-Y fit at the SAME A."""
    rows=[]
    for target in ("choice","logit","probability"):
        valid=validity_by_target[target]
        for block in blocks:
            row=three_way_gap(
                nine[("analytic",target)],
                nine[("formula_y",target)],
                nine[("nn_y",target)],
                block,validity=valid,channel=target)
            rows.append(dict(target=target,block=block,**row))
    return rows
